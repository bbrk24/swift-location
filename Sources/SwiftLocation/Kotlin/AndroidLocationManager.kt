package org.bbrk24.swiftlocation

import android.content.Context
import android.location.LocationManager
import android.location.provider.ProviderProperties

class AndroidLocationManager(context: Context) {
    private val locationManager = context.getSystemService(Context.LOCATION_SERVICE) as LocationManager

    // Determine the most appropriate provider, given what's currently enabled. The scoring criteria
    // this uses is subject to change.
    private fun getProvider(needsFineAccuracy: Boolean): String {
        if (locationManager.isProviderEnabled(LocationManager.FUSED_PROVIDER)) {
            return LocationManager.FUSED_PROVIDER
        }
        
        val providers = locationManager.getProviders(true).map {
            it to locationManager.getProviderProperties(it)
        }
        
        return providers.maxBy {
            val (name, properties) = it
            // Don't use the passive provider. It simply provides a way to observe location fixes
            // generated by other providers.
            if (name == LocationManager.PASSIVE_PROVIDER) {
                Int.MIN_VALUE
            } else {
                // Rank the provider by various criteria. More important criteria get larger values.
                var score = 0
                
                if (needsFineAccuracy) {
                    score += when (properties.accuracy) {
                        ProviderProperties.ACCURACY_COARSE -> 0
                        ProviderProperties.ACCURACY_FINE -> 1
                    } shl 7
                }
                
                val additionalFeatureSupport = booleanArrayOf(
                    provider.hasAltitudeSupport(),
                    provider.hasBearingSupport(),
                    provider.hasSpeedSupport()
                ).count { it }
                score += additionalFeatureSupport shl 5
                
                if (!provider.hasMonetaryCost()) {
                    score += 1 shl 4
                }
                
                score += when (properties.powerUsage) {
                    ProviderProperties.POWER_USAGE_LOW -> 3
                    ProviderProperties.POWER_USAGE_MEDIUM -> 2
                    ProviderProperties.POWER_USAGE_HIGH -> 1
                } shl 2
                
                val networkScore = booleanArrayOf(
                    provider.hasNetworkRequirement(),
                    provider.hasCellRequirement()
                ).count { !it }
                score += networkScore shl 0
                
                score
            }
        }.first
    }
}
